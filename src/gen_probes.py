#!/usr/bin/env python3
#
# PgBouncer - Lightweight connection pooler for PostgreSQL.
#
# Generate include/probes.h from src/probes.d.
#
# Two modes:
#
#   gen_probes.py --dtrace <dtrace> <probes.d> <out.h>
#       Run the real dtrace header generator and rename the generated
#       PGBOUNCER_* macros to TRACE_PGBOUNCER_* (mirrors what PostgreSQL's
#       build does with sed).  Used when the build is configured with
#       --enable-dtrace / -Ddtrace=enabled.
#
#   gen_probes.py --dummy <probes.d> <out.h>
#       Parse probes.d and emit a header of empty macros (plus _ENABLED()
#       guards defined to 0), so that probe call sites compile away when
#       tracing is disabled.  Needs no dtrace binary, so it works anywhere
#       (including Windows).

import os
import re
import subprocess
import sys
import tempfile

PROBE_RE = re.compile(r"probe\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(([^;]*)\)\s*;", re.DOTALL)
BLOCK_COMMENT_RE = re.compile(r"/\*.*?\*/", re.DOTALL)
LINE_COMMENT_RE = re.compile(r"//[^\n]*")


def parse_probes(text):
    """Return a list of (macro_suffix, argument_count) for each probe."""
    # Strip comments first so prose like "probe name(args);" in a comment is
    # not mistaken for a probe declaration.
    text = BLOCK_COMMENT_RE.sub("", text)
    text = LINE_COMMENT_RE.sub("", text)
    probes = []
    for m in PROBE_RE.finditer(text):
        name = m.group(1)
        args = m.group(2).strip()
        if args == "" or args == "void":
            argc = 0
        else:
            argc = len([a for a in args.split(",") if a.strip()])
        # dtrace collapses each "__" to "_" and uppercases the whole name.
        suffix = name.replace("__", "_").upper()
        probes.append((suffix, argc))
    return probes


def gen_dummy(d_path, out_path):
    with open(d_path) as f:
        probes = parse_probes(f.read())

    out = [
        "/* Automatically generated by gen_probes.py --dummy. Do not edit. */",
        "",
        "#ifndef PGBOUNCER_PROBES_H",
        "#define PGBOUNCER_PROBES_H",
        "",
    ]
    for suffix, argc in probes:
        macro = "TRACE_PGBOUNCER_" + suffix
        if argc:
            params = ", ".join(f"arg{i + 1}" for i in range(argc))
            voids = " ".join(f"(void)(arg{i + 1});" for i in range(argc))
            out.append(f"#define {macro}({params}) do {{ {voids} }} while (0)")
        else:
            out.append(f"#define {macro}() do {{ }} while (0)")
        out.append(f"#define {macro}_ENABLED() (0)")
        out.append("")
    out.append("#endif")
    out.append("")

    with open(out_path, "w") as f:
        f.write("\n".join(out))


def gen_real(dtrace, d_path, out_path):
    tmpdir = tempfile.mkdtemp(prefix="pgb-probes-")
    tmp = os.path.join(tmpdir, "probes.h")
    try:
        subprocess.check_call([dtrace, "-h", "-s", d_path, "-o", tmp])
        with open(tmp) as f:
            text = f.read()
        # Uppercase macros are PGBOUNCER_*; prefix them with TRACE_ for a
        # stable, collision-resistant name.  The lowercase semaphore symbols
        # (pgbouncer_*_semaphore) are untouched.
        text = text.replace("PGBOUNCER_", "TRACE_PGBOUNCER_")
        with open(out_path, "w") as f:
            f.write(text)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)
        os.rmdir(tmpdir)


def main(argv):
    if len(argv) >= 2 and argv[1] == "--dummy" and len(argv) == 4:
        gen_dummy(argv[2], argv[3])
        return 0
    if len(argv) >= 2 and argv[1] == "--dtrace" and len(argv) == 5:
        gen_real(argv[2], argv[3], argv[4])
        return 0
    sys.stderr.write(
        "usage: gen_probes.py --dummy <probes.d> <out.h>\n"
        "       gen_probes.py --dtrace <dtrace> <probes.d> <out.h>\n"
    )
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
